/**
 * Build artifact generator: WebUI/js/fx_presets_data/*.js + WebUI/js/factory_fx_presets.js
 * Source of truth: WebUI/data/factory_fx_presets.json
 *
 * Generates 4 categorized preset modules and a loader.
 * Run with: npm run build:presets
 */

const fs = require('fs');
const path = require('path');

const JSON_PATH = path.join(__dirname, '..', 'WebUI', 'data', 'factory_fx_presets.json');
const OUTPUT_DIR = path.join(__dirname, '..', 'WebUI', 'js', 'fx_presets_data');
const LOADER_PATH = path.join(__dirname, '..', 'WebUI', 'js', 'factory_fx_presets.js');

// Type classification: each array of fxType values (0..56)
// fxType in JSON is stored as normalized 0..1 float, e.g. 0.02857 ≈ type 1
const CATEGORIES = {
    reverbs:    { types: [1,2,3,4,5,6,22,26,27,28,52,53], file: 'fx_presets_reverbs.js',    var: 'FX_PRESETS_REVERBS' },
    delays:     { types: [12,13,14,15,21,23,24,25,39,40,41,42,43,44,45], file: 'fx_presets_delays.js', var: 'FX_PRESETS_DELAYS' },
    modulation: { types: [9,10,11,16,17,20,36,37,38,46,47,48], file: 'fx_presets_modulation.js', var: 'FX_PRESETS_MODULATION' },
};

function build() {
    if (!fs.existsSync(JSON_PATH)) {
        throw new Error('Source JSON not found: ' + JSON_PATH);
    }

    const raw = fs.readFileSync(JSON_PATH, 'utf8');
    let data;
    try {
        data = JSON.parse(raw);
    } catch (e) {
        throw new Error('Invalid JSON in ' + JSON_PATH + ': ' + e.message);
    }

    if (!Array.isArray(data)) {
        throw new Error('Expected an array of presets in ' + JSON_PATH);
    }

    // Ensure output directory exists
    if (!fs.existsSync(OUTPUT_DIR)) {
        fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    }

    // Convert normalized fxType (0..1 float) to integer type ID (0..56)
    const getTypeId = (preset) => Math.round(preset.type * 56);

    // Classify presets
    const classified = {
        reverbs:    [],
        delays:     [],
        modulation: [],
        advanced:   [],
    };

    // Track classified item IDs to avoid duplicates in advanced
    const classifiedIds = new Set();

    for (const catName of ['reverbs', 'delays', 'modulation']) {
        const cat = CATEGORIES[catName];
        classified[catName] = data.filter(p => {
            const typeId = getTypeId(p);
            if (cat.types.includes(typeId)) {
                classifiedIds.add(p.name + '|' + p.type);
                return true;
            }
            return false;
        });
    }

    // Advanced = all presets not in any other category
    classified.advanced = data.filter(p => {
        const key = p.name + '|' + p.type;
        return !classifiedIds.has(key);
    });

    const total = data.length;
    const sums = {
        reverbs:    classified.reverbs.length,
        delays:     classified.delays.length,
        modulation: classified.modulation.length,
        advanced:   classified.advanced.length,
    };
    const sum = Object.values(sums).reduce((a, b) => a + b, 0);
    if (sum !== total) {
        console.warn('Warning: classified ' + sum + '/' + total + ' presets (mismatch)');
    }

    const HEADER_COMMENT = '/**\n * @purpose Factory FX presets — ';

    // Write category files
    for (const [catName, cat] of Object.entries(CATEGORIES)) {
        const filePath = path.join(OUTPUT_DIR, cat.file);
        const content = HEADER_COMMENT + catName + ' category.\n * @purpose_en Factory FX presets for ' + catName + '.\n * ⚠️ GENERATED FILE — Do not edit manually.\n * Source: WebUI/data/factory_fx_presets.json\n */\n\nwindow.' + cat.var + ' = ' + JSON.stringify(classified[catName], null, 2) + ';\n';
        fs.writeFileSync(filePath, content, 'utf8');
        console.log('  ✓ ' + cat.file + ' (' + classified[catName].length + ' presets)');
    }

    // Write advanced file
    const advPath = path.join(OUTPUT_DIR, 'fx_presets_advanced.js');
    const advContent = HEADER_COMMENT + 'advanced/experimental category.\n * @purpose_en Factory FX presets for advanced effects.\n * ⚠️ GENERATED FILE — Do not edit manually.\n */\n\nwindow.FX_PRESETS_ADVANCED = ' + JSON.stringify(classified.advanced, null, 2) + ';\n';
    fs.writeFileSync(advPath, advContent, 'utf8');
    console.log('  ✓ fx_presets_advanced.js (' + classified.advanced.length + ' presets)');

    // Write loader (combines all 4 arrays via Object.assign)
    const loaderContent = '/**\n * @purpose Loader for categorized factory FX presets.\n * ⚠️ GENERATED FILE — Do not edit manually.\n * Generated by scripts/build-fx-presets.js\n */\n\nwindow.FACTORY_FX_PRESETS = Object.assign(\n    [],\n    window.FX_PRESETS_REVERBS || [],\n    window.FX_PRESETS_DELAYS || [],\n    window.FX_PRESETS_MODULATION || [],\n    window.FX_PRESETS_ADVANCED || []\n);\n';
    fs.writeFileSync(LOADER_PATH, loaderContent, 'utf8');
    console.log('  ✓ factory_fx_presets.js (loader)');

    console.log('\n✅ Build complete: ' + total + ' presets → 4 category files + loader');
}

try {
    build();
} catch (e) {
    console.error('❌ Build failed: ' + e.message);
    process.exit(1);
}
